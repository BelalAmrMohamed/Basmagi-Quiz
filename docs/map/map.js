import fs from "fs";
import path from "path";

// Settings

const outputMapPath = "docs/map/context-map.txt";
const IGNORE_EXT = [];
const EXCEPTION_NAMES = ["README.md", "robots.txt"];
const IGNORE_HIDDEN_FILES = true;

const MAP_DESCRIPTION = `// ${outputMapPath} 
A generated file that provides a visual representation of the project's directory structure. It is intended to help developers and contributors understand the organization of the project and locate files more easily. The map is generated by traversing the project directory and listing all files and folders, while respecting .gitignore rules and other specified ignore settings.
The map is useful for quickly identifying the layout of the project, understanding the relationships between different components, and navigating the codebase. It can also serve as a reference for new contributors to get acquainted with the project's structure.`;

// Determine project root directory
const scriptDir = import.meta.dirname;
const rootDir = path.resolve(scriptDir, "../../");
const outputFile = path.join(rootDir, outputMapPath);

// Parse .gitignore into Regex rules
function getGitignoreRules() {
  const gitignorePath = path.join(rootDir, ".gitignore");
  const rules = [/(^|\/)\.git($|\/)/];

  if (fs.existsSync(gitignorePath)) {
    const lines = fs.readFileSync(gitignorePath, "utf-8").split("\n");
    for (let line of lines) {
      line = line.trim();
      if (!line || line.startsWith("#")) continue;

      let escaped = line.replace(/[.+^${}()|[\]\\]/g, "\\$&");
      escaped = escaped.replace(/\*/g, ".*").replace(/\?/g, ".");

      if (escaped.startsWith("\\/")) {
        rules.push(new RegExp("^" + escaped.substring(2) + "($|/)"));
      } else {
        rules.push(new RegExp("(^|/)" + escaped + "($|/)"));
      }
    }
  }
  return rules;
}

const ignoreRegexes = getGitignoreRules();

function isIgnored(itemPath, isDir, itemName) {
  if (EXCEPTION_NAMES.includes(itemName)) return false;
  if (IGNORE_HIDDEN_FILES && itemName.startsWith(".")) return true;
  if (IGNORE_EXT.some((ext) => itemName.endsWith(ext))) return true;

  const relativePath = path.relative(rootDir, itemPath).replace(/\\/g, "/");
  return ignoreRegexes.some((regex) => regex.test(relativePath) || (isDir && regex.test(relativePath + "/")));
}

function generateTree() {
  const outputDir = path.dirname(outputFile);
  if (!fs.existsSync(outputDir)) fs.mkdirSync(outputDir, { recursive: true });

  const outputStream = fs.createWriteStream(outputFile, { encoding: "utf-8" });

  // Insert description at the top of the file
  if (MAP_DESCRIPTION && MAP_DESCRIPTION.trim()) {
    outputStream.write(`${MAP_DESCRIPTION.trim()}\n\n`);
    outputStream.write(`------------------------------------------------\n\n`);
  }

  outputStream.write(`${path.basename(rootDir)}/\n`);

  function walkDir(currentPath, prefix = "") {
    let allItems = fs.readdirSync(currentPath);
    const files = [];
    const dirs = [];

    allItems.forEach((item) => {
      if (item === ".git") return;

      const fullPath = path.join(currentPath, item);
      const isDir = fs.statSync(fullPath).isDirectory();

      if (isIgnored(fullPath, isDir, item)) return;

      if (isDir) dirs.push(item);
      else files.push(item);
    });

    files.sort();
    dirs.sort();

    const sortedItems = [...files, ...dirs];

    sortedItems.forEach((item, i) => {
      const isLast = i === sortedItems.length - 1;
      const connector = isLast ? "└── " : "├── ";
      const fullPath = path.join(currentPath, item);
      const isDir = fs.statSync(fullPath).isDirectory();

      outputStream.write(`${prefix}${connector}${item}${isDir ? "/" : ""}\n`);

      if (isDir) {
        const newPrefix = prefix + (isLast ? "    " : "│   ");
        walkDir(fullPath, newPrefix);
      }
    });
  }

  walkDir(rootDir);
  outputStream.end();

  // Display the relative path from the project root instead of the absolute path
  const relativeOutput = path.relative(rootDir, outputFile);
  console.log(`Done! Check: ${relativeOutput}`);
}

generateTree();