/** Build a translate function. Unknown keys fall back to the English text. */
export function createT(lang: Lang, extraAr: Record<string, string> = {}): T {
  const table = lang === 'ar' ? { ...AR, ...extraAr } : null;
  return (en, vars) => {
    let s = table?.[en] ?? en;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
    return s;
  };
}
