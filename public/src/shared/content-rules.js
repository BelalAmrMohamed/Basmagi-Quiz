/**
 * @param {{title?:string, description?:string, source?:string, questions?:any[]}} input
 *   Question shapes: MCQ { q, options, correct, multiSelect?, explanation? }
 *                    Essay { q, answer, explanation? }   (no options)
 * @returns {{errors:{code,path,message}[], warnings:{code,path,message}[]}}
 */
export function checkQuiz(input) {
  const c = makeCollector();

  const title = str(input?.title);
  if (!title) c.err("TITLE_REQUIRED", "title", "title مطلوب: أضف عنواناً واضحاً للامتحان.");
  else if (title.length > LIMITS.quizTitle) {
    c.err("TITLE_TOO_LONG", "title", `title أطول من ${LIMITS.quizTitle} حرف (الحالي ${title.length}) — اختصره.`);
  }

  const description = str(input?.description);
  if (description.length > LIMITS.quizDescription) {
    c.err("DESCRIPTION_TOO_LONG", "description", `description أطول من ${LIMITS.quizDescription} حرف (الحالي ${description.length}) — اختصره.`);
  }
  if (!description) c.warn("DESCRIPTION_EMPTY", "description", "description فارغ — يُفضّل وصف قصير لما يقيسه الامتحان.");

  const source = str(input?.source);
  if (source && !isHttpUrl(source)) {
    c.err("SOURCE_INVALID", "source", 'source يجب أن يكون رابطاً كاملاً يبدأ بـ https:// ولا شيء غيره — إن لم يوجد رابط اتركه "" (فارغاً).');
  }
  if (source.length > LIMITS.quizSource) {
    c.err("SOURCE_TOO_LONG", "source", `source أطول من ${LIMITS.quizSource} حرف (الحالي ${source.length}).`);
  }

  const qs = input?.questions;
  if (!Array.isArray(qs) || !qs.length) {
    c.err("NO_QUESTIONS", "questions", "questions يجب أن تكون مصفوفة غير فارغة (سؤال واحد على الأقل).");
    return c;
  }
  if (qs.length > LIMITS.quizQuestions) {
    c.err("TOO_MANY_QUESTIONS", "questions", `عدد الأسئلة ${qs.length} يتجاوز الحد الأقصى ${LIMITS.quizQuestions}.`);
  }

  let noExplanation = 0;
  const seen = new Map();
  const mathQs = [];
  const tfLangQs = [];

  qs.forEach((q, i) => {
    const n = i + 1;
    const path = `questions[${i}]`;
    const text = str(q?.q);
    const at = `السؤال ${n}${text ? ` («${clip(text)}»)` : ""}`;

    if (!text) c.err("Q_TEXT_REQUIRED", path, `السؤال ${n}: نص السؤال (q) مفقود — اكتب نص السؤال.`);
    if (!str(q?.explanation)) noExplanation++;

    const key = text.toLowerCase().replace(/\s+/g, " ");
    if (key) {
      if (seen.has(key)) c.warn("DUPLICATE_QUESTION", path, `${at}: مكرر للسؤال ${seen.get(key)}.`);
      else seen.set(key, n);
    }

    const hasOptions = Array.isArray(q?.options) && q.options.length > 0;
    const answer = str(q?.answer);

    const mathText = [q?.q, q?.explanation, answer, ...(hasOptions ? q.options : [])].join("\n");
    if (hasPlainTextMath(mathText)) mathQs.push(n);

    if (!hasOptions) {
      if (!answer) {
        c.err("ESSAY_ANSWER_REQUIRED", path, `${at}: سؤال مقالي بلا إجابة نموذجية — أضف answer (الإجابة المرجعية)، أو أضف options + correct ليصبح اختيار من متعدد.`);
      }
      return;
    }

    const options = q.options.map((o) => str(o));
    if (options.length < LIMITS.optionsMin || options.length > LIMITS.quizOptionsMax) {
      c.err("OPTIONS_COUNT", path, `${at}: عدد الخيارات ${options.length} — المسموح ${LIMITS.optionsMin} إلى ${LIMITS.quizOptionsMax}.`);
    }
    if (options.some((o) => !o)) {
      c.err("OPTION_EMPTY", path, `${at}: يوجد خيار فارغ — كل الخيارات يجب أن تحتوي نصاً.`);
    }
    if (new Set(options.map((o) => o.toLowerCase())).size !== options.length) {
      c.warn("OPTION_DUPLICATE", path, `${at}: يحتوي على خيارات مكررة.`);
    }

    const rawCorrect = Array.isArray(q.correct) ? q.correct : q.correct === undefined || q.correct === null ? [] : [q.correct];
    if (!rawCorrect.length) {
      c.err("CORRECT_MISSING", path, `${at}: حدّد الإجابة الصحيحة — الحقل correct مفقود (فهرس يبدأ من 0، مثال: 0 للخيار الأول). لن يُخمَّن.`);
    } else {
      const nums = rawCorrect.map(Number);
      const bad = nums.filter((x) => !Number.isInteger(x) || x < 0 || x >= options.length);
      if (bad.length) {
        c.err("CORRECT_RANGE", path, `${at}: correct=${JSON.stringify(q.correct)} خارج النطاق — الفهارس الصالحة 0..${options.length - 1} (يبدأ العدّ من 0).`);
      } else if (q.multiSelect === true && new Set(nums).size < 2) {
        c.warn("MULTISELECT_ONE_CORRECT", path, `${at}: multiSelect=true لكن توجد إجابة صحيحة واحدة فقط.`);
      }
    }

    const lbl = trueFalseLabelLang(options);
    if (lbl) {
      const ql = languageOf(text);
      if ((lbl === "ar" && ql === "en") || (lbl === "en" && ql === "ar")) tfLangQs.push(n);
    }
  });

  if (noExplanation) c.warn("NO_EXPLANATION", "questions", `${noExplanation} سؤال بلا explanation — الشرح هو ما يجعل الامتحان تعليمياً.`);
  if (mathQs.length) {
    c.warn("PLAIN_TEXT_MATH", "questions", `الأسئلة ${listPositions(mathQs)} تحتوي معادلات/رموز رياضية بنص عادي (مثل x^2 أو √ أو ≤) — اكتبها بـ LaTeX: $...$ داخل السطر أو $$...$$ منفصلة.`);
  }
  if (tfLangQs.length) {
    c.warn("TF_LABEL_LANGUAGE", "questions", `الأسئلة ${listPositions(tfLangQs)} (صح/خطأ): لغة الخيارين لا تطابق لغة السؤال — استخدم ["صح","خطأ"] للعربية و["True","False"] للإنجليزية.`);
  }

  return c;
}

// ── Lesson ──────────────────────────────────────────────────────────────────
/**
 * @param {object} input  { title, description, source, sections|content.sections }
 * @param {{publish?: boolean, sectionsOnly?: boolean}} [opts]
 *   publish=true → lesson-reference ids must be UUIDs;
 *   sectionsOnly=true → skip title/description/source (callers that validate them separately)
 */
export function checkLesson(input, opts = {}) {
  const c = makeCollector();
  const publish = opts.publish === true;

  if (!opts.sectionsOnly) {
    const title = str(input?.title);
    if (!title) c.err("LESSON_TITLE_REQUIRED", "title", "title مطلوب: أضف عنواناً للدرس.");
    else if (title.length > LIMITS.lessonTitle) {
      c.err("LESSON_TITLE_TOO_LONG", "title", `title أطول من ${LIMITS.lessonTitle} حرف (الحالي ${title.length}).`);
    }
    const description = str(input?.description);
    if (description.length > LIMITS.lessonDescription) {
      c.err("LESSON_DESCRIPTION_TOO_LONG", "description", `description أطول من ${LIMITS.lessonDescription} حرف (الحالي ${description.length}).`);
    }
    if (!description) c.warn("LESSON_DESCRIPTION_EMPTY", "description", "description فارغ.");
    const source = str(input?.source);
    if (source && !isHttpUrl(source)) {
      c.err("LESSON_SOURCE_INVALID", "source", 'source يجب أن يكون رابطاً كاملاً يبدأ بـ https:// ولا شيء غيره — إن لم يوجد رابط اتركه "" (فارغاً).');
    }
    if (source.length > LIMITS.lessonSource) {
      c.err("LESSON_SOURCE_TOO_LONG", "source", `source أطول من ${LIMITS.lessonSource} حرف.`);
    }
  }

  const rawSections = Array.isArray(input?.sections)
    ? input.sections
    : Array.isArray(input?.content?.sections)
      ? input.content.sections
      : null;
  if (!rawSections || !rawSections.length) {
    c.err("NO_SECTIONS", "sections", "sections يجب أن تكون مصفوفة غير فارغة (قسم واحد على الأقل).");
    return c;
  }
  if (rawSections.length > LIMITS.lessonSections) {
    c.err("TOO_MANY_SECTIONS", "sections", `عدد الأقسام ${rawSections.length} يتجاوز الحد الأقصى ${LIMITS.lessonSections}.`);
  }

  const mathAt = [];
  rawSections.forEach((s, sIdx) => {
    const sn = sIdx + 1;
    const secTitle = str(s?.title);
    if (!secTitle) c.err("SECTION_TITLE_REQUIRED", `sections[${sIdx}]`, `القسم ${sn}: العنوان مطلوب.`);
    else if (secTitle.length > LIMITS.sectionTitle) {
      c.err("SECTION_TITLE_TOO_LONG", `sections[${sIdx}]`, `القسم ${sn}: العنوان أطول من ${LIMITS.sectionTitle} حرف.`);
    }

    const rawBlocks = Array.isArray(s?.blocks)
      ? s.blocks
      : typeof s?.content === "string"
        ? [{ type: "markdown", body: s.content }]
        : [];
    if (!rawBlocks.length) c.warn("SECTION_EMPTY", `sections[${sIdx}]`, `القسم ${sn}${secTitle ? ` («${clip(secTitle)}»)` : ""} بلا عناصر.`);
    if (rawBlocks.length > LIMITS.blocksPerSection) {
      c.err("TOO_MANY_BLOCKS", `sections[${sIdx}]`, `القسم ${sn}: ${rawBlocks.length} عنصراً — الحد الأقصى ${LIMITS.blocksPerSection} عنصر في القسم الواحد. قسّمه إلى أقسام.`);
    }

    rawBlocks.forEach((b, bIdx) => {
      if (!b || typeof b !== "object") return;
      const bn = bIdx + 1;
      const path = `sections[${sIdx}].blocks[${bIdx}]`;
      const at = `القسم ${sn} / العنصر ${bn}`;
      const type = b.type || (b.prompt || b.q ? "question" : "markdown");

      if (type === "markdown") {
        const body = String(b.body ?? b.content ?? "");
        if (!body.trim()) c.warn("MARKDOWN_EMPTY", path, `${at}: نص markdown فارغ.`);
        if (body.length > LIMITS.markdownBody) {
          c.err("MARKDOWN_TOO_LONG", path, `${at}: النص ${body.length} حرف ويتجاوز ${LIMITS.markdownBody} — قسّمه إلى عدة عناصر.`);
        }
        if (hasPlainTextMath(body)) mathAt.push(`${sn}/${bn}`);
      } else if (type === "media") {
        const url = str(b.url);
        if (!url) c.err("MEDIA_URL_REQUIRED", path, `${at}: رابط الوسائط (url) مفقود.`);
        else if (!isHttpUrl(url) && !url.startsWith("./") && !url.startsWith("/")) {
          c.err("MEDIA_URL_INVALID", path, `${at}: url غير صالح — يجب أن يبدأ بـ https://.`);
        }
      } else if (type === "quizRef") {
        if (!str(b.quizId)) c.err("QUIZ_REF_REQUIRED", path, `${at}: quizId مفقود — اختر الامتحان المرتبط (ابحث عنه بـ search_catalog).`);
      } else if (type === "lesson-reference" || type === "lessonRef") {
        const lessonId = str(b.lessonId ?? b.lessonRefId);
        if (!lessonId) c.err("LESSON_REF_REQUIRED", path, `${at}: lessonId مفقود — اختر الدرس المرتبط (ابحث عنه بـ search_catalog).`);
        else if (publish && !UUID_RE.test(lessonId)) {
          c.err("LESSON_REF_NOT_UUID", path, `${at}: lessonId يجب أن يكون UUID لدرس منشور (من search_catalog) وليس معرّفاً محلياً.`);
        }
      } else if (type === "question") {
        const prompt = str(b.prompt ?? b.q);
        const qAt = `${at}${prompt ? ` («${clip(prompt)}»)` : ""}`;
        if (!prompt) c.err("PROMPT_REQUIRED", path, `${at}: نص السؤال (prompt) مفقود.`);
        else if (prompt.length > LIMITS.promptMax) c.err("PROMPT_TOO_LONG", path, `${qAt}: نص السؤال يتجاوز ${LIMITS.promptMax} حرف.`);
        const explanation = str(b.explanation);
        if (explanation.length > LIMITS.explanationMax) {
          c.err("EXPLANATION_TOO_LONG", path, `${qAt}: explanation يتجاوز ${LIMITS.explanationMax} حرف.`);
        }
        const hasOptions = Array.isArray(b.options) && b.options.length > 0;
        const modelAnswer = str(b.modelAnswer ?? b.answer);
        const isEssay = b.questionKind === "essay" || (!hasOptions && !!modelAnswer);

        const mathText = [b.prompt ?? b.q, b.explanation, modelAnswer, ...(hasOptions ? b.options : [])].join("\n");
        if (hasPlainTextMath(mathText)) mathAt.push(`${sn}/${bn}`);

        if (isEssay) {
          if (!modelAnswer) c.err("MODEL_ANSWER_REQUIRED", path, `${qAt}: السؤال المقالي يحتاج modelAnswer (الإجابة النموذجية).`);
          else if (modelAnswer.length > LIMITS.modelAnswerMax) {
            c.err("MODEL_ANSWER_TOO_LONG", path, `${qAt}: modelAnswer يتجاوز ${LIMITS.modelAnswerMax} حرف.`);
          }
        } else {
          if (!hasOptions) {
            c.err("OPTIONS_REQUIRED", path, `${qAt}: سؤال بلا options — أضف خيارات (2 إلى ${LIMITS.optionsMax}) أو اجعله مقالياً (questionKind:"essay" + modelAnswer).`);
          }
          const options = (hasOptions ? b.options : []).map((o) => str(o));
          if (hasOptions && (options.length < LIMITS.optionsMin || options.length > LIMITS.optionsMax)) {
            c.err("OPTIONS_COUNT", path, `${qAt}: عدد الخيارات ${options.length} — المسموح ${LIMITS.optionsMin} إلى ${LIMITS.optionsMax}.`);
          }
          if (options.some((o) => !o)) c.err("OPTION_EMPTY", path, `${qAt}: يوجد خيار فارغ — كل الخيارات يجب أن تحتوي نصاً.`);
          const rawCorrect = Array.isArray(b.correctIndexes)
            ? b.correctIndexes
            : Array.isArray(b.correct)
              ? b.correct
              : Number.isInteger(b.correctIndex)
                ? [b.correctIndex]
                : Number.isInteger(b.correct)
                  ? [b.correct]
                  : [];
          if (hasOptions) {
            if (!rawCorrect.length) {
              c.err("CORRECT_MISSING", path, `${qAt}: حدّد الإجابة الصحيحة — correctIndex مفقود (يبدأ من 0). لن يُخمَّن.`);
            } else if (rawCorrect.some((x) => !Number.isInteger(Number(x)) || Number(x) < 0 || Number(x) >= options.length)) {
              c.err("CORRECT_RANGE", path, `${qAt}: الفهرس الصحيح خارج النطاق 0..${options.length - 1} (يبدأ العدّ من 0).`);
            } else if (new Set(rawCorrect.map(Number)).size !== rawCorrect.length) {
              c.warn("CORRECT_DUPLICATE", path, `${qAt}: فهارس الإجابة الصحيحة مكررة — سيتم دمجها.`);
            }
          }
          if (!explanation) c.warn("NO_EXPLANATION", path, `${qAt}: سؤال بلا explanation.`);
        }
      } else {
        c.err("UNKNOWN_BLOCK_TYPE", path, `${at}: type="${type}" غير معروف (المسموح: markdown, media, quizRef, lesson-reference, question).`);
      }
    });
  });

  if (mathAt.length) {
    c.warn("PLAIN_TEXT_MATH", "sections", `العناصر (قسم/عنصر) ${listPositions(mathAt)} تحتوي معادلات/رموز رياضية بنص عادي (مثل x^2 أو √ أو ≤) — اكتبها بـ LaTeX: $...$ داخل السطر أو $$...$$ منفصلة.`);
  }

  try {
    const bytes = new TextEncoder().encode(JSON.stringify({ sections: rawSections })).length;
    if (bytes > LIMITS.lessonBytes) {
      c.err("LESSON_TOO_LARGE", "sections", `حجم الدرس ${Math.round(bytes / 1000)}KB يتجاوز ${LIMITS.lessonBytes / 1000}KB — قسّمه إلى دروس.`);
    }
  } catch (_) { /* non-serializable input is caught elsewhere */ }

  return c;
}

// ── Notebook ────────────────────────────────────────────────────────────────
const NOTEBOOK_CELL_ID_RE = /^[A-Za-z0-9_-]+$/;

/**
 * Builds the canonical stored document { schemaVersion, cells } from raw cells,
 * assigning stable ids (`cell-N`) to cells that have none. It does NOT fix
 * invalid data (unknown types stay as given so checkNotebook can reject them).
 */
export function normalizeNotebookContent(rawCells, language, runtime = "matlab") {
  const cells = Array.isArray(rawCells) ? rawCells : [];
  const used = new Set(cells.map((c) => str(c?.id)).filter(Boolean));
  let n = 0;
  const nextId = () => {
    let id;
    do { id = `cell-${++n}`; } while (used.has(id));
    used.add(id);
    return id;
  };
  const lang = NOTEBOOK_LANGUAGES.includes(language) ? language : undefined;
  return {
    schemaVersion: NOTEBOOK_SCHEMA_VERSION,
    ...(lang ? { language: lang } : {}),
    cells: cells.map((c) => ({
      id: str(c?.id) || nextId(),
      type: typeof c?.type === "string" ? c.type : "",
      source: typeof c?.source === "string" ? c.source : c?.source == null ? "" : String(c.source),
      ...(runtime === "cpp" && c?.type === "code" && typeof c?.stdin === "string" ? { stdin: c.stdin } : {}),
    })),
  };
}

/**
 * Asset manifest entry: { path, mime, size, sha256, url }. `path` is the flat file name the
 * notebook code uses (imread("cat.png"), ![](cat.png)); `url` is the public Storage URL.
 * Returns clean entries (unknown keys dropped); invalid input is reported by checkNotebookAssets.
 */
export function normalizeNotebookAssets(assets) {
  if (!Array.isArray(assets)) return [];
  return assets.map((a) => ({
    path: str(a?.path),
    mime: str(a?.mime),
    size: Number(a?.size),
    sha256: str(a?.sha256).toLowerCase(),
    url: str(a?.url),
  }));
}

const ASSET_PATH_RE = /^[^\\/:*?"<>|\u0000-\u001f.][^\\/:*?"<>|\u0000-\u001f]{0,99}$/;

/** @param {object} c issue collector from checkNotebook */
export function checkNotebookAssets(assets, c) {
  if (!Array.isArray(assets)) { c.err("ASSETS_INVALID", "assets", "assets يجب أن تكون مصفوفة."); return; }
  if (assets.length > LIMITS.notebookAssets) {
    c.err("TOO_MANY_ASSETS", "assets", `عدد الملفات ${assets.length} يتجاوز الحد الأقصى ${LIMITS.notebookAssets}.`);
  }
  const seen = new Set();
  assets.forEach((a, i) => {
    const n = i + 1;
    const p = `assets[${i}]`;
    const ext = String(a?.path || "").split(".").pop().toLowerCase();
    if (!ASSET_PATH_RE.test(String(a?.path || ""))) c.err("ASSET_PATH_INVALID", p, `الملف ${n}: اسم الملف غير صالح.`);
    else if (seen.has(a.path.toLowerCase())) c.err("ASSET_DUPLICATE", p, `الملف ${n}: الاسم "${a.path}" مكرر.`);
    else seen.add(a.path.toLowerCase());
    if (!NOTEBOOK_ASSET_MIME[ext] || NOTEBOOK_ASSET_MIME[ext] !== a?.mime) {
      c.err("ASSET_TYPE_INVALID", p, `الملف ${n}: النوع غير مسموح (المسموح: ${Object.keys(NOTEBOOK_ASSET_MIME).join(", ")}).`);
    }
    if (!Number.isInteger(a?.size) || a.size < 1 || a.size > LIMITS.notebookAssetBytes) {
      c.err("ASSET_SIZE_INVALID", p, `الملف ${n}: الحجم يجب أن يكون بين 1 بايت و${LIMITS.notebookAssetBytes / 1048576}MB.`);
    }
    if (!/^[0-9a-f]{64}$/.test(String(a?.sha256 || ""))) c.err("ASSET_HASH_INVALID", p, `الملف ${n}: sha256 غير صالح.`);
    if (!HTTP_URL_RE.test(String(a?.url || "")) || !String(a.url).includes(NOTEBOOK_ASSET_URL_MARKER)) {
      c.err("ASSET_URL_INVALID", p, `الملف ${n}: الرابط يجب أن يكون من مخزن notebook-assets.`);
    }
  });
}

/** Names from `paths` that cell sources actually reference (case-insensitive substring; over-matching is harmless). */
export function referencedNotebookAssets(cells, paths) {
  const text = (Array.isArray(cells) ? cells : []).map((c) => String(c?.source || "")).join("\n").toLowerCase();
  return paths.filter((p) => text.includes(String(p).toLowerCase()));
}

/**
 * @param {object} input  { title, description, source, runtime, content:{schemaVersion,cells} | cells }
 * @param {{contentOnly?: boolean}} [opts]
 *   contentOnly=true → skip title/description/source (callers that validate them separately)
 */
export function checkNotebook(input, opts = {}) {
  const c = makeCollector();

  if (!opts.contentOnly) {
    const title = str(input?.title);
    if (!title) c.err("NOTEBOOK_TITLE_REQUIRED", "title", "title مطلوب: أضف عنواناً للدفتر.");
    else if (title.length > LIMITS.notebookTitle) {
      c.err("NOTEBOOK_TITLE_TOO_LONG", "title", `title أطول من ${LIMITS.notebookTitle} حرف (الحالي ${title.length}).`);
    }
    const description = str(input?.description);
    if (description.length > LIMITS.notebookDescription) {
      c.err("NOTEBOOK_DESCRIPTION_TOO_LONG", "description", `description أطول من ${LIMITS.notebookDescription} حرف (الحالي ${description.length}).`);
    }
    if (!description) c.warn("NOTEBOOK_DESCRIPTION_EMPTY", "description", "description فارغ.");
    const source = str(input?.source);
    if (source && !isHttpUrl(source)) {
      c.err("NOTEBOOK_SOURCE_INVALID", "source", 'source يجب أن يكون رابطاً كاملاً يبدأ بـ https:// ولا شيء غيره — إن لم يوجد رابط اتركه "" (فارغاً).');
    }
    if (source.length > LIMITS.notebookSource) {
      c.err("NOTEBOOK_SOURCE_TOO_LONG", "source", `source أطول من ${LIMITS.notebookSource} حرف.`);
    }
    const runtime = str(input?.runtime);
    if (!runtime) {
      c.err("RUNTIME_REQUIRED", "runtime", `runtime مطلوب (المسموح: ${NOTEBOOK_RUNTIMES.join(", ")}) — لا يتم افتراض قيمة.`);
    } else if (!NOTEBOOK_RUNTIMES.includes(runtime)) {
      c.err("RUNTIME_UNSUPPORTED", "runtime", `runtime="${runtime}" غير مدعوم (المسموح: ${NOTEBOOK_RUNTIMES.join(", ")}).`);
    }
  }

  const doc = input?.content && typeof input.content === "object" && !Array.isArray(input.content) ? input.content : null;
  if (doc && doc.schemaVersion !== undefined && doc.schemaVersion !== NOTEBOOK_SCHEMA_VERSION) {
    c.err("SCHEMA_VERSION_UNSUPPORTED", "content.schemaVersion", `schemaVersion=${JSON.stringify(doc.schemaVersion)} غير مدعوم (المدعوم: ${NOTEBOOK_SCHEMA_VERSION}).`);
  }
  const language = input?.language !== undefined ? input.language : doc?.language;
  if (language !== undefined && language !== "" && !NOTEBOOK_LANGUAGES.includes(language)) {
    c.err("NOTEBOOK_LANGUAGE_INVALID", "language", `language=${JSON.stringify(language)} غير مدعوم (المسموح: ${NOTEBOOK_LANGUAGES.join(", ")}).`);
  }
  const rawCells = Array.isArray(input?.cells) ? input.cells : Array.isArray(doc?.cells) ? doc.cells : null;
  if (!rawCells || !rawCells.length) {
    c.err("NO_CELLS", "cells", "cells يجب أن تكون مصفوفة غير فارغة (خلية واحدة على الأقل).");
    return c;
  }
  if (rawCells.length > LIMITS.notebookCells) {
    c.err("TOO_MANY_CELLS", "cells", `عدد الخلايا ${rawCells.length} يتجاوز الحد الأقصى ${LIMITS.notebookCells}.`);
  }

  const seenIds = new Set();
  let codeCells = 0;
  rawCells.forEach((cell, i) => {
    const n = i + 1;
    const path = `cells[${i}]`;
    if (!cell || typeof cell !== "object" || Array.isArray(cell)) {
      c.err("CELL_NOT_OBJECT", path, `الخلية ${n}: يجب أن تكون كائناً { id, type, source }.`);
      return;
    }
    const type = cell.type;
    if (!NOTEBOOK_CELL_TYPES.includes(type)) {
      c.err("UNKNOWN_CELL_TYPE", path, `الخلية ${n}: type=${JSON.stringify(type)} غير معروف (المسموح: ${NOTEBOOK_CELL_TYPES.join(", ")}).`);
    }
    if (typeof cell.source !== "string") {
      c.err("CELL_SOURCE_NOT_STRING", path, `الخلية ${n}: source يجب أن يكون نصاً.`);
    } else {
      if (cell.source.length > LIMITS.notebookCellSource) {
        c.err("CELL_TOO_LONG", path, `الخلية ${n}: ${cell.source.length} حرف وتتجاوز ${LIMITS.notebookCellSource} — قسّمها إلى عدة خلايا.`);
      }
      if (!cell.source.trim()) c.warn("CELL_EMPTY", path, `الخلية ${n}: فارغة.`);
    }
    if (cell.stdin !== undefined && (str(input?.runtime) !== "cpp" || type !== "code" || typeof cell.stdin !== "string" || cell.stdin.length > LIMITS.notebookCellStdin)) {
      c.err("CELL_STDIN_INVALID", `${path}.stdin`, `الخلية ${n}: stdin مسموح لخلايا C++ فقط وبحد أقصى ${LIMITS.notebookCellStdin} حرف.`);
    }
    if (type === "code") codeCells++;
    const id = cell.id;
    if (id !== undefined && id !== null && id !== "") {
      if (typeof id !== "string" || id.length > LIMITS.notebookCellId || !NOTEBOOK_CELL_ID_RE.test(id)) {
        c.err("CELL_ID_INVALID", path, `الخلية ${n}: id يجب أن يكون حروفاً/أرقاماً/_/- فقط وبطول ≤ ${LIMITS.notebookCellId}.`);
      } else if (seenIds.has(id)) {
        c.err("CELL_ID_DUPLICATE", path, `الخلية ${n}: id="${id}" مكرر.`);
      } else seenIds.add(id);
    }
  });
  const assetsRaw = input && input.content && input.content.assets;
  if (assetsRaw !== undefined) checkNotebookAssets(assetsRaw, c);
  if (!codeCells) c.warn("NO_CODE_CELLS", "cells", "لا توجد أي خلية كود — الدفتر يحتوي نصاً فقط.");

  try {
    const bytes = new TextEncoder().encode(JSON.stringify({ cells: rawCells })).length;
    if (bytes > LIMITS.notebookBytes) {
      c.err("NOTEBOOK_TOO_LARGE", "cells", `حجم الدفتر ${Math.round(bytes / 1000)}KB يتجاوز ${LIMITS.notebookBytes / 1000}KB — قسّمه إلى دفاتر.`);
    }
  } catch (_) { /* non-serializable input is caught elsewhere */ }

  return c;
}
