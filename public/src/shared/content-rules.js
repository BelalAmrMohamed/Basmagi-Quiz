const HTTP_URL_RE = /^https?:\/\/\S+$/i;
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

const str = (v) => (v === undefined || v === null ? "" : String(v)).trim();
export const isHttpUrl = (s) => HTTP_URL_RE.test(String(s || ""));

const clip = (s, n = 40) => {
  const t = String(s ?? "").replace(/\s+/g, " ").trim();
  return t.length > n ? t.slice(0, n - 1) + "…" : t;
};

/** Returns a clean `source`: a real http(s) link, or "" (also drops the legacy AI sentence). */
export function cleanSource(value) {
  const s = str(value);
  if (!s || s === LEGACY_AI_SOURCE) return "";
  return isHttpUrl(s) ? s : "";
}

/** Drops only the legacy "generated by AI" sentence; any other value is kept (so validation can flag it). */
export function stripLegacySource(value) {
  const s = value === undefined || value === null ? "" : String(value);
  return s.trim() === LEGACY_AI_SOURCE ? "" : s;
}

/** True when `value` is non-empty text that is not an acceptable source link. */
export function isBadSource(value) {
  const s = str(value);
  return !!s && !isHttpUrl(s);
}

/** Numbered Arabic list of issues, capped (used by pages and the upload API). */
export function formatIssueList(issues, max = 20) {
  const list = (issues || []).map((i) => (typeof i === "string" ? i : i.message));
  const shown = list.slice(0, max).map((m, i) => `${i + 1}. ${m}`);
  if (list.length > max) shown.push(`… و${list.length - max} مشكلة أخرى.`);
  return shown.join("\n");
}

function makeCollector() {
  const errors = [];
  const warnings = [];
  return {
    errors,
    warnings,
    err: (code, path, message) => errors.push({ code, path, message }),
    warn: (code, path, message) => warnings.push({ code, path, message }),
  };
}

// ── Math / language heuristics (warnings only) ─────────────────────────────

function stripMathAndCode(text) {
  return String(text || "")
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/`[^`]*`/g, " ")
    .replace(/\$\$[\s\S]*?\$\$/g, " ")
    .replace(/\$[^$\n]*\$/g, " ");
}

const PLAIN_MATH_RES = [
  /\b[a-zA-Z0-9)\]]\s?\^\s?[\w{(-]/, // x^2, (a+b)^2
  /\b(?:sqrt|root)\s*\(/i, // sqrt(x)
  /[√∑∫∞≤≥≠±∂∆πθλμσΩ]/, // unicode math symbols
  /[²³⁴⁵⁶⁷⁸⁹⁰¹ⁿ]/, // unicode superscripts
  /\b\d+\s*\/\s*\d+\b(?=\s*[=+\-*×÷)])/, // 1/2 =
];

export function hasPlainTextMath(text) {
  const t = stripMathAndCode(text);
  return PLAIN_MATH_RES.some((re) => re.test(t));
}

function languageOf(text) {
  const s = String(text || "");
  const ar = (s.match(/[\u0600-\u06FF]/g) || []).length;
  const lat = (s.match(/[A-Za-z]/g) || []).length;
  if (ar === 0 && lat === 0) return "none";
  return ar >= lat ? "ar" : "en";
}

function trueFalseLabelLang(options) {
  if (!Array.isArray(options) || options.length !== 2) return null;
  const set = options.map((o) => str(o).toLowerCase());
  if (set.includes("صح") && set.includes("خطأ")) return "ar";
  if (set.includes("true") && set.includes("false")) return "en";
  return null;
}

function listPositions(nums, max = 6) {
  const shown = nums.slice(0, max).join("، ");
  return nums.length > max ? `${shown} … (+${nums.length - max})` : shown;
}

